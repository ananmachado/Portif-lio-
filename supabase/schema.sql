-- O servidor sincroniza automaticamente o usuário autenticado para public.users.
-- Para tornar a sua conta administradora, defina OWNER_EMAIL na Vercel com o
-- mesmo e-mail da conta. No próximo login, a coluna role será atualizada para admin.

-- ---------------------------------------------------------------------------
-- Data API permissions (required on new Supabase projects created with the
-- opt-in Data API exposure model).
--
-- This app never queries these tables directly from the browser. All database
-- access goes through the Vercel server using a Supabase Secret/service-role
-- key, so only service_role needs table privileges. RLS remains enabled as a
-- defense-in-depth boundary for any accidental client-side access.
-- ---------------------------------------------------------------------------

grant usage on schema public to service_role;

grant select, insert, update, delete on table
  public.users,
  public.portfolio_settings,
  public.categories,
  public.projects,
  public.project_blocks
to service_role;

grant usage, select on all sequences in schema public to service_role;

revoke all on table
  public.users,
  public.portfolio_settings,
  public.categories,
  public.projects,
  public.project_blocks
from anon, authenticated;

alter table public.users enable row level security;
alter table public.portfolio_settings enable row level security;
alter table public.categories enable row level security;
alter table public.projects enable row level security;
alter table public.project_blocks enable row level security;

-- Keep future tables/sequences server-only by default when this schema is
-- extended later.
alter default privileges for role postgres in schema public
  grant select, insert, update, delete on tables to service_role;
alter default privileges for role postgres in schema public
  grant usage, select on sequences to service_role;
